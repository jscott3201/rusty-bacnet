//! Resolve Device declarations while the session still owns an unstarted link.
use crate::session::EndpointSession;
use bacnet_transport::port::TransportPort;
use bacnet_types::error::Error;
use std::sync::Arc;
use tokio::sync::RwLock;

impl<T: TransportPort + 'static> EndpointSession<T> {
    pub(super) async fn prepare_identity(&mut self) -> Result<(), Error> {
        let Some(identity) = self.identity.as_ref() else {
            return Ok(());
        };
        let identity = identity.resolve(self.local_receive_capacity)?;
        // Validate before replacing configuration or constructing an object.
        if let Some(database) = &self.database {
            let database = database.read().await;
            if let Some(oid) = database.selected_device() {
                identity.validate_device(database.get(&oid).expect("selected under guard"))?;
            }
        }
        if self.database.is_none() {
            self.database = Some(Arc::new(RwLock::new(identity.build_database()?)));
        }
        self.client_config.max_apdu_length = identity.max_apdu_length();
        self.config.max_apdu_length = identity.max_apdu_length();
        self.identity = Some(identity);
        Ok(())
    }
}

/// Keep generated declarations local to a successful preflight. In particular,
/// failure or cancellation must not turn a later identity correction into a
/// mismatch against a stock Device generated by the abandoned attempt.
struct IdentityPreparation<'a, T: TransportPort + 'static> {
    session: &'a mut EndpointSession<T>,
    original: Option<bacnet_objects::DeviceIdentity>,
    had_database: bool,
    client_capacity: u16,
    session_capacity: u16,
    /// The database was bound to the identity's Device (#2227).
    bound: bool,
    committed: bool,
}

impl<T: TransportPort + 'static> Drop for IdentityPreparation<'_, T> {
    fn drop(&mut self) {
        if !self.committed {
            self.session.identity = self.original.take();
            self.session.client_config.max_apdu_length = self.client_capacity;
            self.session.config.max_apdu_length = self.session_capacity;
            if !self.had_database {
                self.session.database = None;
            } else if self.bound
                && let Some(mut database) = self
                    .session
                    .database
                    .as_ref()
                    .and_then(|db| db.try_write().ok())
            {
                // Release the binding a failed or cancelled preflight made.
                // Nothing in the preflight still holds the guard by now.
                database.bind_local_device_internal(None);
            }
        }
    }
}

impl<T: TransportPort + 'static> EndpointSession<T> {
    pub(super) async fn prepare_start(
        &mut self,
    ) -> Result<Option<crate::source_audit::recipient::SourceRoutes>, Error> {
        let mut preparation = IdentityPreparation {
            original: self.identity.clone(),
            had_database: self.database.is_some(),
            client_capacity: self.client_config.max_apdu_length,
            session_capacity: self.config.max_apdu_length,
            session: self,
            bound: false,
            committed: false,
        };
        // The full server the session will build, refused before anything
        // changes (#2617).
        preparation.session.default_server();
        preparation.session.check_server_builder()?;
        preparation.session.validate_segmentation().await?;
        preparation.session.prepare_identity().await?;
        preparation.session.check_server_settings().await?;
        let routes = preparation.session.prepare_source_audit_reporter()?;
        // Bind the database to the identity's Device from here on, as a
        // server's is, even beside a lower one added later (#2227); with no
        // identity it keeps its lowest Device. A preflight that fails or is
        // cancelled after this releases the binding again (Drop).
        preparation.session.bind_identity_device()?;
        preparation.bound = true;
        preparation.session.prepare_registered_port().await?;
        preparation.committed = true;
        Ok(routes)
    }

    /// The session's roles take no segmented request or answer yet: refuse
    /// an identity, or an attached database's Device, that declares
    /// segmentation other than NO_SEGMENTATION.
    async fn validate_segmentation(&self) -> Result<(), Error> {
        use bacnet_types::enums::{PropertyIdentifier, Segmentation};
        use bacnet_types::primitives::PropertyValue;
        if self
            .identity
            .as_ref()
            .is_some_and(|identity| identity.segmentation() != Segmentation::NO_SEGMENTATION)
        {
            return Err(Error::Encoding(
                "EndpointSession roles require segmentation NO_SEGMENTATION".into(),
            ));
        }
        if let Some(database) = self.database.as_ref() {
            let database = database.read().await;
            if let Some(oid) = database.selected_device() {
                let device = database
                    .get(&oid)
                    .expect("selected under same database guard");
                let mode =
                    device.read_property(PropertyIdentifier::SEGMENTATION_SUPPORTED, None)?;
                if mode
                    != PropertyValue::Enumerated(u32::from(Segmentation::NO_SEGMENTATION.to_raw()))
                {
                    return Err(Error::Encoding(
                        "EndpointSession selected Device requires segmentation NO_SEGMENTATION"
                            .into(),
                    ));
                }
            }
        }
        Ok(())
    }
}

impl<T: TransportPort + 'static> EndpointSession<T> {
    /// Bind the startup database to the identity's Device, or release it to
    /// the lowest Device without an identity. It takes the guard without
    /// waiting: a database the application holds locked fails the preflight,
    /// leaving the session ready to retry.
    fn bind_identity_device(&mut self) -> Result<(), Error> {
        let device = self.identity.as_ref().map(|identity| identity.device_oid());
        if let Some(database) = &self.database {
            database
                .try_write()
                .map_err(|_| Error::Encoding("endpoint database is locked at start".into()))?
                .bind_local_device_internal(device);
        }
        Ok(())
    }
}
