//! The receive-only monitor's statistics engine on rings of real master
//! cores (#958): what the engine infers from the wire matches what the
//! simulator knows the cores did.

mod common;

use std::time::Duration as StdDuration;

use bacnet_mstp_codec::{decode_frame_in_place, FrameType};
use bacnet_mstp_sim::{Fault, MasterSpec, Sim, SimConfig, WireFrame};
use bacnet_transport::mstp::monitor::{LineErrorKind, LineEvent, MaxMaster, MonitorStats};

use common::*;

/// Feed every frame the simulator put on the line to a statistics engine,
/// stamped when its last octet ended, as a monitor on the line would see it.
fn monitor(frames: &[WireFrame]) -> MonitorStats {
    let mut stats = MonitorStats::new(BAUD, StdDuration::ZERO);
    for frame in frames {
        let at = StdDuration::from_nanos(frame.end.as_nanos());
        let mut octets = frame.octets.clone();
        let event = match decode_frame_in_place(&mut octets) {
            Ok((decoded, wire_length)) if frame.is_clean() => LineEvent::Frame {
                header: decoded.header,
                wire_length,
            },
            _ => LineEvent::Error {
                kind: LineErrorKind::Malformed,
                destination: None,
                octets: frame.octets.len(),
            },
        };
        stats.record(at, &event);
    }
    stats
}

/// The issue's ring on real cores: masters 1, 2 and 5, station 2 with
/// Max_Master 3. Station 1 finds 2 and stops there; station 2 polls 3 and
/// 0 and finds 1; nobody polls 5, which only answers station 1's requests.
#[test]
fn a_misconfigured_ring_of_cores_is_read_correctly() {
    let mut sim = Sim::new(SimConfig::new(BAUD));
    sim.add_master(MasterSpec::new(1, 127, BAUD))
        .add_master(MasterSpec::new(2, 3, BAUD))
        .add_master(MasterSpec::new(5, 127, BAUD));
    for second in 1..=4u64 {
        sim.enqueue(ms(second * 1_000), 1, 5, &npdu(true, second as u8));
    }
    sim.run_until(ms(6_000));
    sim.assert_no_violations();
    let frames = sim.frames();
    let stats = monitor(frames);

    assert_eq!(stats.present_stations().collect::<Vec<_>>(), [1, 2, 5]);
    assert_eq!(stats.station(5).unwrap().tokens_received, 0);
    assert_eq!(
        stats.station(2).unwrap().max_master,
        Some(MaxMaster::Exact(3))
    );
    assert_eq!(
        stats
            .station(5)
            .unwrap()
            .frames_sent
            .data_not_expecting_reply,
        4
    );
    // The engine's counts are the simulator's.
    let tokens = frames
        .iter()
        .filter(|frame| frame.frame_type() == Some(FrameType::TOKEN))
        .count() as u64;
    assert!(tokens > 100, "{tokens}");
    assert_eq!(stats.token_passes, tokens);
    assert_eq!(stats.frames.total(), frames.len() as u64);
    assert_eq!(
        stats.station(2).unwrap().frames_sent.poll_for_master,
        sent_by(frames, 2, FrameType::POLL_FOR_MASTER).len() as u64
    );
    // Startup is the only silence long enough to lose a token in, and it
    // comes before any traffic, so it doesn't count.
    assert_eq!(stats.lost_tokens, 0);
}

/// Every master loses power at once; one comes back, waits out
/// T_no_token and generates a new token: one lost token, regenerated by it.
#[test]
fn a_ring_that_falls_silent_shows_one_lost_token() {
    let mut sim = ring(BAUD, &[1, 2], 127);
    sim.inject(ms(2_000), Fault::PowerOff { station: 1 })
        .inject(ms(2_000), Fault::PowerOff { station: 2 })
        .inject(ms(2_300), Fault::PowerOn { station: 1 });
    sim.run_until(ms(4_000));
    // Part way through its first sweep, the estimate is a lower bound.
    let early = monitor(sim.frames());
    let Some(MaxMaster::AtLeast(partial)) = early.station(1).unwrap().max_master else {
        panic!("{:?}", early.station(1));
    };
    assert!((2..127).contains(&partial), "{partial}");
    sim.run_until(ms(7_000));
    let stats = monitor(sim.frames());

    assert_eq!(stats.lost_tokens, 1);
    let lost = stats.last_lost_token.unwrap();
    assert_eq!(lost.regenerated_by, Some(1));
    assert!(lost.silence > StdDuration::from_millis(800), "{lost:?}");
    // Alone, station 1 polls every address up to its Max_Master in turn,
    // then wraps to 0, which pins it down.
    assert_eq!(
        stats.station(1).unwrap().max_master,
        Some(MaxMaster::Exact(127))
    );
}
